    private void btnAddRepairActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddRepairActionPerformed

        try {

            // Read repair information
            String repairId = txtRepairId.getText().trim();
            String assetId = txtRepairAssetId.getText().trim();

            double repairCost = Double.parseDouble(
                    txtRepairRequestCost.getText().trim());

            String status = cmbRepairStatus.getSelectedItem().toString();

            // Validate repair ID and asset ID
            if (repairId.isEmpty() || assetId.isEmpty()) {
                throw new IllegalArgumentException(
                        "Repair ID and Asset ID are required"
                );
            }

            // Check if asset exists in inventory
            boolean assetFound = false;

            for (Asset asset : inventory.searchAsset(assetId)) {

                if (asset.getAssetId().equalsIgnoreCase(assetId)) {
                    assetFound = true;
                    break;
                }
            }

            if (!assetFound) {
                throw new IllegalArgumentException(
                        "Asset not found: " + assetId
                );
            }

            // Create a repair request
            RepairRequest repair = new RepairRequest(
                    repairId,
                    assetId,
                    repairCost,
                    status
            );

            // Save repair permanently in SQLite
            DatabaseManager.saveRepair(repair);

// Register repair in memory
            allocationManager.addRepairRequest(repair);

            // Get the repairs table model
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblRepairs.getModel();

            // Add repair request to table
            model.addRow(new Object[]{
                repair.getRepairId(),
                repair.getAssetId(),
                repair.getRepairCost(),
                repair.getStatus()
            });

            // Display success message
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Repair registered successfully: " + repairId
            );

        } catch (NumberFormatException e) {

            // Handle invalid repair cost
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter a valid repair cost.",
                    "Input Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

        } catch (IllegalArgumentException e) {

            // Handle repair validation errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Repair Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        } catch (java.sql.SQLException e) {

            // Handle database errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Database error: " + e.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnAddRepairActionPerformed

