    private void btnUpdateRepairActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateRepairActionPerformed

        try {

            // Read repair ID and selected status
            String repairId = txtRepairId.getText().trim();
            String newStatus = cmbRepairStatus.getSelectedItem().toString();

            // Save repair status permanently in SQLite
            DatabaseManager.updateRepairStatus(repairId, newStatus);

            // Update repair status in memory
            allocationManager.updateRepairStatus(repairId, newStatus);

            // Get the repairs table model
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblRepairs.getModel();

            // Find the repair in the table
            for (int i = 0; i < model.getRowCount(); i++) {

                String currentId = model.getValueAt(i, 0).toString();

                if (currentId.equalsIgnoreCase(repairId)) {

                    // Update the status column
                    model.setValueAt(newStatus, i, 3);
                    break;
                }
            }

            // Display success message
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Repair status updated successfully: " + repairId
            );

        } catch (IllegalArgumentException e) {

            // Handle invalid repair IDs or status
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Update Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        } catch (java.sql.SQLException e) {

            // Handle database update errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Database error: " + e.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }


    }//GEN-LAST:event_btnUpdateRepairActionPerformed

    private void btnAllocateAssetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAllocateAssetActionPerformed

        try {

            // Read allocation information
            String allocationId = txtAllocationId.getText().trim();
            String assetId = txtAllocationAssetId.getText().trim();
            String departmentId = txtDepartmentId.getText().trim();

            // Validate required fields
            if (allocationId.isEmpty() || assetId.isEmpty()
                    || departmentId.isEmpty()) {

                throw new IllegalArgumentException(
                        "All allocation fields are required"
                );
            }

            // Find the asset in inventory
            Asset selectedAsset = null;

            for (Asset asset : inventory.searchAsset(assetId)) {

                if (asset.getAssetId().equalsIgnoreCase(assetId)) {
                    selectedAsset = asset;
                    break;
                }
            }

            if (selectedAsset == null) {
                throw new IllegalArgumentException(
                        "Asset not found: " + assetId
                );
            }

            // Check department ID
            if (!department1.getDepartmentId().equalsIgnoreCase(departmentId)) {
                throw new IllegalArgumentException(
                        "Department not found: " + departmentId
                );
            }

            // Save allocation permanently in SQLite
            DatabaseManager.saveAllocation(
                    allocationId,
                    selectedAsset.getAssetId(),
                    department1.getDepartmentId(),
                    "IT Department"
            );

            // Update allocation in memory
            allocationManager.allocateAsset(
                    allocationId,
                    selectedAsset,
                    department1
            );

            // Get the allocations table model
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblAllocations.getModel();

            // Add the allocation to the table
            model.addRow(new Object[]{
                allocationId,
                selectedAsset.getAssetId(),
                departmentId
            });

            // Update asset status in the inventory table
            javax.swing.table.DefaultTableModel assetModel
                    = (javax.swing.table.DefaultTableModel) tblAssets.getModel();

            for (int i = 0; i < assetModel.getRowCount(); i++) {

                String currentId = assetModel.getValueAt(i, 0).toString();

                if (currentId.equalsIgnoreCase(assetId)) {

                    assetModel.setValueAt("Allocated", i, 6);
                    break;
                }
            }

            // Display success message
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Allocation successful: " + allocationId
            );

        } catch (IllegalArgumentException e) {

            // Handle allocation errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Allocation Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        } catch (java.sql.SQLException e) {

            // Handle database allocation errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Database error: " + e.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }


    }//GEN-LAST:event_btnAllocateAssetActionPerformed

