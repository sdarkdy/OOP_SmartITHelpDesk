    private void btnUnallocateAssetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUnallocateAssetActionPerformed

        try {
            // Read Allocation ID
            String allocationId = txtAllocationId.getText().trim();

            if (allocationId.isEmpty()) {
                throw new IllegalArgumentException(
                        "Please enter an Allocation ID.");
            }

            // Confirm unallocation
            int confirm = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Unallocate " + allocationId + "?",
                    "Confirm Unallocation",
                    javax.swing.JOptionPane.YES_NO_OPTION
            );

            if (confirm != javax.swing.JOptionPane.YES_OPTION) {
                return;
            }

            // Unallocate in SQLite
            String assetId = DatabaseManager.unallocateAsset(allocationId);

            // Update allocation manager
            allocationManager.removeAllocation(allocationId);

            // Update asset status in memory
            for (Asset asset : inventory.getAllAssets()) {
                if (asset.getAssetId().equalsIgnoreCase(assetId)) {
                    asset.setStatus("Available");
                    break;
                }
            }

            // Remove allocation from table
            javax.swing.table.DefaultTableModel allocationModel
                    = (javax.swing.table.DefaultTableModel) tblAllocations.getModel();

            for (int i = allocationModel.getRowCount() - 1; i >= 0; i--) {
                if (allocationModel.getValueAt(i, 0)
                        .toString().equalsIgnoreCase(allocationId)) {
                    allocationModel.removeRow(i);
                }
            }

            // Update Assets table
            javax.swing.table.DefaultTableModel assetModel
                    = (javax.swing.table.DefaultTableModel) tblAssets.getModel();

            for (int i = 0; i < assetModel.getRowCount(); i++) {
                if (assetModel.getValueAt(i, 0)
                        .toString().equalsIgnoreCase(assetId)) {
                    assetModel.setValueAt("Available", i, 6);
                    break;
                }
            }

            // Clear allocation inputs
            btnClearAllocationActionPerformed(null);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Asset " + assetId + " unallocated successfully."
            );

        } catch (IllegalArgumentException | java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Unallocation Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnUnallocateAssetActionPerformed

    // Escape special characters in CSV values
    private String csvValue(String value) {

        if (value == null) {
            return "";
        }

        // Escape quotation marks
        String escaped = value.replace("\"", "\"\"");

        // Quote values containing commas, quotes or newlines
        if (escaped.contains(",")
                || escaped.contains("\"")
                || escaped.contains("\n")
                || escaped.contains("\r")) {

            return "\"" + escaped + "\"";
        }

        return escaped;
    }

    // Read CSV records including quoted values
    private java.util.ArrayList<String[]> parseCsv(String content) {

        java.util.ArrayList<String[]> records
                = new java.util.ArrayList<>();

        java.util.ArrayList<String> fields
                = new java.util.ArrayList<>();

        StringBuilder value = new StringBuilder();

        boolean inQuotes = false;
        boolean afterQuote = false;
        boolean fieldStarted = false;

        // Remove UTF-8 BOM if present
        if (content.startsWith("\uFEFF")) {
            content = content.substring(1);
        }

        // Process CSV characters
        for (int i = 0; i < content.length(); i++) {

            char c = content.charAt(i);

            if (inQuotes) {

                if (c == '"') {

                    // Handle escaped quotation marks
                    if (i + 1 < content.length()
                            && content.charAt(i + 1) == '"') {

                        value.append('"');
                        i++;

                    } else {
                        inQuotes = false;
                        afterQuote = true;
                    }

                } else {
                    value.append(c);
                }

            } else if (c == ',') {

                // Finish the current column
                fields.add(value.toString());
                value.setLength(0);
                afterQuote = false;
                fieldStarted = false;

            } else if (c == '\n' || c == '\r') {

                // Finish the current record
                fields.add(value.toString());

                records.add(fields.toArray(new String[0]));

                fields = new java.util.ArrayList<>();
                value.setLength(0);
                afterQuote = false;
                fieldStarted = false;

                // Handle Windows line endings
                if (c == '\r'
                        && i + 1 < content.length()
                        && content.charAt(i + 1) == '\n') {
                    i++;
                }

            } else if (c == '"') {

                // Quotes must begin a field
                if (fieldStarted || afterQuote) {
                    throw new IllegalArgumentException(
                            "Invalid quotation mark in CSV"
                    );
                }

                inQuotes = true;
                fieldStarted = true;

            } else {

                // Reject characters after a closing quote
                if (afterQuote) {
                    throw new IllegalArgumentException(
                            "Invalid character after CSV quotation"
                    );
                }

                value.append(c);
                fieldStarted = true;
            }
        }

        // Reject incomplete quoted fields
        if (inQuotes) {
            throw new IllegalArgumentException(
                    "Unclosed quotation mark in CSV"
            );
        }

        // Add final record when present
        if (fieldStarted || afterQuote
                || value.length() > 0 || !fields.isEmpty()) {

            fields.add(value.toString());
            records.add(fields.toArray(new String[0]));
        }

        return records;
    }

