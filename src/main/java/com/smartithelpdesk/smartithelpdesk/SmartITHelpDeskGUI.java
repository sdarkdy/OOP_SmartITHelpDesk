    private void btnRegisterAssetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterAssetActionPerformed
        try {
            // Read common asset information
            String assetId = txtAssetId.getText().trim();
            String description = txtDescription.getText().trim();
            String assetType = cmbAssetType.getSelectedItem().toString();

            double purchaseValue = Double.parseDouble(
                    txtPurchaseValue.getText().trim());

            double repairCost = Double.parseDouble(
                    txtRepairCost.getText().trim());

            int quantity = Integer.parseInt(
                    txtQuantity.getText().trim());

            String status = cmbStatus.getSelectedItem().toString();
            // Read updated mass
            double massKg = Double.parseDouble(
                    txtMassKg.getText().trim());

            if (!Double.isFinite(massKg) || massKg <= 0) {
                throw new IllegalArgumentException(
                        "Mass must be greater than zero.");
            }

            // Create an asset based on its type
            Asset newAsset;

            if (assetType.equals("Computer")) {

                // Read computer information
                int ram = Integer.parseInt(txtRam.getText().trim());
                int storage = Integer.parseInt(txtStorage.getText().trim());

                newAsset = new ComputerAsset(
                        assetId,
                        description,
                        purchaseValue,
                        repairCost,
                        quantity,
                        status,
                        ram,
                        storage
                );

            } else if (assetType.equals("Furniture")) {

                // Read furniture information
                String material = txtMaterial.getText().trim();
                boolean safetyPassed = chkSafetyPassed.isSelected();

                newAsset = new FurnitureAsset(
                        assetId,
                        description,
                        purchaseValue,
                        repairCost,
                        quantity,
                        status,
                        material,
                        safetyPassed
                );

            } else {
                throw new IllegalArgumentException("Invalid asset type");
            }

            // Store mass in the asset object
            newAsset.setMassKg(massKg);
            // Check for duplicate assets in memory
            for (Asset existing : inventory.getAllAssets()) {
                if (existing.getAssetId().equalsIgnoreCase(newAsset.getAssetId())) {
                    throw new IllegalArgumentException(
                            "Duplicate Asset ID: " + newAsset.getAssetId()
                    );
                }
            }

            // Save asset permanently in SQLite
            DatabaseManager.saveAsset(newAsset);

            // Register asset in memory
            inventory.addAsset(newAsset);

            // Get the inventory table model
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblAssets.getModel();

            // Add the asset to the table
            model.addRow(new Object[]{
                newAsset.getAssetId(),
                newAsset.getDescription(),
                assetType,
                newAsset.getPurchaseValue(),
                newAsset.getRepairCost(),
                newAsset.getQuantity(),
                newAsset.getStatus(),
                newAsset.getMassKg()
            });

            // Show success message
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Asset registered successfully: " + assetId
            );

        } catch (NumberFormatException e) {

            // Handle invalid numbers
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter valid numeric values.",
                    "Input Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

        } catch (IllegalArgumentException e) {

            // Handle registration errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Registration Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );

        } catch (java.sql.SQLException e) {

            // Handle database saving errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Database error: " + e.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnRegisterAssetActionPerformed

