    public SmartITHelpDeskGUI() {
        initComponents();

        // Initialize SQLite database
        DatabaseManager.initializeDatabase();

        // Set initial asset fields
        cmbAssetTypeActionPerformed(null);

        // Load saved assets from SQLite
        try {

            // Get inventory table model
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblAssets.getModel();

            for (Asset asset : DatabaseManager.loadAssets()) {

                // Register asset in memory
                inventory.addAsset(asset);

                // Identify asset type
                String type = asset instanceof ComputerAsset
                        ? "Computer" : "Furniture";

                // Display saved asset in table
                model.addRow(new Object[]{
                    asset.getAssetId(),
                    asset.getDescription(),
                    type,
                    asset.getPurchaseValue(),
                    asset.getRepairCost(),
                    asset.getQuantity(),
                    asset.getStatus(),
                    asset.getMassKg()
                });
            }

            // Load saved repair requests from SQLite
            javax.swing.table.DefaultTableModel repairModel
                    = (javax.swing.table.DefaultTableModel) tblRepairs.getModel();

            for (RepairRequest repair : DatabaseManager.loadRepairs()) {

                // Restore repair in AllocationManager
                allocationManager.addRepairRequest(repair);

                // Display repair in Repairs table
                repairModel.addRow(new Object[]{
                    repair.getRepairId(),
                    repair.getAssetId(),
                    repair.getRepairCost(),
                    repair.getStatus()
                });
            }

            // Load saved allocations from SQLite
            javax.swing.table.DefaultTableModel allocationModel
                    = (javax.swing.table.DefaultTableModel) tblAllocations.getModel();

            for (String[] allocation : DatabaseManager.loadAllocations()) {

                // Display saved allocation in table
                allocationModel.addRow(new Object[]{
                    allocation[0], // Allocation ID
                    allocation[1], // Asset ID
                    allocation[2] // Department ID
                });
            }

        } catch (java.sql.SQLException | IllegalArgumentException e) {

            // Display database loading errors
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Failed to load assets: " + e.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }

